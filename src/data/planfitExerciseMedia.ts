/** Official Planfit guide page for a mapped local exercise. */
export function getPlanfitExerciseSourceUrl(exerciseId: string): string {
  const match = planfitExerciseMatches[exerciseId]
  return match ? `${PLANFIT_EXERCISE_ORIGIN}/${match.slug}` : ''
}

/** Hosted thumbnail and continuously looping, watermarked Planfit animation. */
export function getPlanfitExerciseMedia(exerciseId: string) {
  const match = planfitExerciseMatches[exerciseId]
  if (!match) {
    return undefined
  }

  return {
    imageUrl: `${PLANFIT_CDN_ORIGIN}/training-image/${match.planfitId}_thumbnail.png`,
    imageAlt: `Planfit ${match.planfitName} demonstration`,
    gifUrl: `${PLANFIT_CDN_ORIGIN}/training-videos-watermarked/${match.planfitId}.mp4`,
    gifAlt: `Planfit ${match.planfitName} looping animation`,
  }
}

